var root = args.Length > 0 ? args[0] : Directory.GetCurrentDirectory();
var recorder = new Recorder();
ShopContext NewContext()
{
    var ctx = new ShopContext(new DbContextOptionsBuilder<ShopContext>()
        .UseSqlServer("Server=lab;Database=Shop;Trusted_Connection=True;TrustServerCertificate=True")
        .AddInterceptors(recorder, new NoConnection())
        .Options);
    ctx.Database.AutoTransactionBehavior = AutoTransactionBehavior.Never;   // nothing to commit against
    return ctx;
}

// Runs an action and returns every command EF Core tried to send (execution is suppressed/aborted).
List<string> Capture(Action<ShopContext> action)
{
    recorder.Commands.Clear();
    using var db = NewContext();
    try { action(db); } catch { /* expected: commands are captured, then aborted */ }
    return [.. recorder.Commands];
}

