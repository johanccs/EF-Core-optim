sealed class Recorder : DbCommandInterceptor
{
    public List<string> Commands { get; } = new();
    public override InterceptionResult<DbDataReader> ReaderExecuting(DbCommand c, CommandEventData e, InterceptionResult<DbDataReader> r)
    { Commands.Add(c.CommandText); return InterceptionResult<DbDataReader>.SuppressWithResult(new OneRowReader()); }
    public override InterceptionResult<int> NonQueryExecuting(DbCommand c, CommandEventData e, InterceptionResult<int> r)
    { Commands.Add(c.CommandText); return InterceptionResult<int>.SuppressWithResult(0); }
    public override InterceptionResult<object> ScalarExecuting(DbCommand c, CommandEventData e, InterceptionResult<object> r)
    { Commands.Add(c.CommandText); return InterceptionResult<object>.SuppressWithResult(0); }
}

// A fake result with one row of plausible values, so EF Core goes on to issue follow-up commands
// (e.g. the child queries of a split query) and we can capture their real SQL too.
sealed class OneRowReader : DbDataReader
{
    bool read;
    public override bool Read() { if (read) return false; read = true; return true; }
    public override Task<bool> ReadAsync(CancellationToken ct) => Task.FromResult(Read());
    public override bool NextResult() => false;
    public override int FieldCount => 64;
    public override bool HasRows => true;
    public override bool IsClosed => false;
    public override int RecordsAffected => 1;
    public override int Depth => 0;
    public override object this[int i] => GetValue(i);
    public override object this[string name] => 1;
    public override bool IsDBNull(int i) => false;
    public override object GetValue(int i) => 1;
    public override int GetValues(object[] values) { for (var i = 0; i < values.Length; i++) values[i] = 1; return values.Length; }
    public override T GetFieldValue<T>(int i) => (T)Sample(typeof(T));
    static object Sample(Type t)
    {
        t = Nullable.GetUnderlyingType(t) ?? t;
        if (t == typeof(string)) return "x";
        if (t == typeof(DateTime)) return new DateTime(2026, 1, 1);
        if (t == typeof(Guid)) return Guid.Empty;
        if (t == typeof(bool)) return true;
        if (t == typeof(byte[])) return new byte[8];
        if (t.IsEnum) return Enum.ToObject(t, 0);
        return Convert.ChangeType(1, t);
    }
    public override bool GetBoolean(int i) => true;
    public override byte GetByte(int i) => 1;
    public override long GetBytes(int i, long o, byte[]? b, int bo, int l) => 0;
    public override char GetChar(int i) => 'x';
    public override long GetChars(int i, long o, char[]? b, int bo, int l) => 0;
    public override string GetDataTypeName(int i) => "int";
    public override DateTime GetDateTime(int i) => new(2026, 1, 1);
    public override decimal GetDecimal(int i) => 1m;
    public override double GetDouble(int i) => 1;
    public override Type GetFieldType(int i) => typeof(int);
    public override float GetFloat(int i) => 1;
    public override Guid GetGuid(int i) => Guid.Empty;
    public override short GetInt16(int i) => 1;
    public override int GetInt32(int i) => 1;
    public override long GetInt64(int i) => 1;
    public override string GetName(int i) => "c" + i;
    public override int GetOrdinal(string name) => 0;
    public override string GetString(int i) => "x";
    public override System.Collections.IEnumerator GetEnumerator() => Array.Empty<object>().GetEnumerator();
}

sealed class NoConnection : DbConnectionInterceptor
{
    public override InterceptionResult ConnectionOpening(DbConnection c, ConnectionEventData e, InterceptionResult r) => InterceptionResult.Suppress();
    public override InterceptionResult ConnectionClosing(DbConnection c, ConnectionEventData e, InterceptionResult r) => InterceptionResult.Suppress();
}

// Course model (Lesson 1) plus Address, used by Lesson 15's cartesian-explosion example.
public class Customer { public int Id { get; set; } public string Name { get; set; } = ""; public string Email { get; set; } = ""; public List<Order> Orders { get; set; } = new(); public List<Address> Addresses { get; set; } = new(); }
public class Address { public int Id { get; set; } public int CustomerId { get; set; } public string Street { get; set; } = ""; public string City { get; set; } = ""; }
public class Order { public int Id { get; set; } public int CustomerId { get; set; } public Customer Customer { get; set; } = null!; public DateTime PlacedUtc { get; set; } public decimal Total { get; set; } }
public class Product { public int Id { get; set; } public string Sku { get; set; } = ""; public string Name { get; set; } = ""; public string Description { get; set; } = ""; public decimal Price { get; set; } public int CategoryId { get; set; } }

public class ShopContext(DbContextOptions<ShopContext> options) : DbContext(options)
{
    public DbSet<Customer> Customers => Set<Customer>();
    public DbSet<Order> Orders => Set<Order>();
    public DbSet<Product> Products => Set<Product>();
    public DbSet<Address> Addresses => Set<Address>();
    protected override void OnModelCreating(ModelBuilder b)
    {
        b.Entity<Customer>().Property(c => c.Name).HasMaxLength(100);
        b.Entity<Order>().Property(o => o.Total).HasPrecision(12, 2);
        b.Entity<Product>().Property(p => p.Price).HasPrecision(10, 2);
    }
}
